// `T.en` and `T.ar` each have their own literal string types per key (e.g.
// appName is the literal "Compux" vs the literal "كومبكس"), which is exactly
// what lets a missing/mistyped key in either language get caught at compile
// time. But it also means `typeof T["en"]` alone is too narrow to describe
// "whichever language object is active" - assigning `T[lang]` (a union of
// both) into that type fails once `lang === 'ar'`. TKeys widens every value
// back to `string` while still enforcing the exact same key set from `en`,
// so both languages satisfy it and a key present in one but not the other
// still fails to typecheck.
export type TKeys = { [K in keyof typeof T['en']]: string };
